#!/usr/bin/env node
/* Discover features and write .cache/features.generated.js, which build.sh splices into the app just before boot.
 *
 *   src/features/<id>/feature.json   manifest   (contracts/feature.schema.json)
 *   src/features/<id>/index.js       the feature: a function body that ends with  return { render, wire };
 *   src/features/<id>/feature.css    optional styles
 *   src/features/<id>/test.js        the feature's own browser test (run by tests/features.test.js)
 *
 * Nothing lists features: a feature exists because its folder does, exactly as a lesson exists because its seed does.
 * Each index.js is wrapped in its own function so two features can never collide on a name. The output is deterministic
 * (sorted by id, no timestamps), so the same set of folders always builds the same bytes, whatever order they were merged.
 * This runs in build.sh and on Vercel, where no packages are installed, so it uses only the standard library; the full
 * schema validation is tools/validate-contracts.js. */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "src", "features");
const OUT = path.join(ROOT, ".cache", "features.generated.js");

function discover() {
  if (!fs.existsSync(DIR)) return [];
  return fs.readdirSync(DIR, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort();
}
function load(id) {
  const base = path.join(DIR, id), problems = [];
  const mf = path.join(base, "feature.json");
  if (!fs.existsSync(mf)) return { id, problems: ["src/features/" + id + "/feature.json is missing"] };
  let manifest;
  try { manifest = JSON.parse(fs.readFileSync(mf, "utf8")); } catch (e) { return { id, problems: ["src/features/" + id + "/feature.json is not valid JSON: " + e.message] }; }
  if (manifest.id !== id) problems.push("manifest id '" + manifest.id + "' must equal its folder name '" + id + "'");
  if (!Array.isArray(manifest.storage)) problems.push("manifest.storage must be an array (use [] for none)");
  for (const f of ["index.js", "test.js"]) if (!fs.existsSync(path.join(base, f))) problems.push("src/features/" + id + "/" + f + " is missing");
  let source = "";
  if (!problems.length) {
    source = fs.readFileSync(path.join(base, "index.js"), "utf8");
    try { new Function(source); } catch (e) { problems.push("src/features/" + id + "/index.js does not compile: " + e.message); }
    if (!/\breturn\b/.test(source)) problems.push("src/features/" + id + "/index.js must end with: return { render, wire };");
  }
  const cssFile = path.join(base, "feature.css");
  return { id, manifest, source, css: fs.existsSync(cssFile) ? fs.readFileSync(cssFile, "utf8") : "", problems };
}

const features = discover().map(load);
const problems = features.flatMap(f => f.problems);
if (problems.length) { problems.forEach(p => console.error("PROBLEM " + p)); console.error("FAILED: " + problems.length + " feature problem(s)"); process.exit(1); }

let out = "/* GENERATED by tools/build-features.js from src/features/*. Do not edit. */\n";
for (const f of features) {
  out += "\n/* feature: " + f.id + " */\n;(function(){\n";
  if (f.css) out += "  (function(){var s=document.createElement('style');s.setAttribute('data-feature','" + f.id + "');s.textContent=" + JSON.stringify(f.css) + ";document.head.appendChild(s)})();\n";
  out += "  const __manifest=" + JSON.stringify(f.manifest) + ";\n";
  out += "  const __feature=(function(){\n" + f.source + "\n  })();\n";
  out += "  registerFeature(__manifest,__feature);\n})();\n";
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
console.log("features: " + (features.length ? features.map(f => f.id).join(", ") : "none") + " (" + features.length + ")");
