# -*- coding: utf-8 -*-
"""Build the CSIR NET 2011-2025 previous-year practice banks.

    python pyq_bank_build.py            write seed/<module>_csir_pyq.json and docs/CSIR_PYQ_BANK.md
    python pyq_bank_build.py --check    exit 1 if the files on disk differ from what would be written

Sources: four MathStats Classes compilations of CSIR NET questions (Probability, Standard Univariate Distributions,
Univariate Distributions, Multivariate Distributions). Each pyq_bank_<source>.py holds one compilation's questions with
the answer and a worked solution. A question that appears in two compilations is kept once, in the file named first in
its `ref`. Every item is routed to the module it tests, so a multivariate-normal question goes to the multivariate
bank and a Poisson-process question to the stochastic bank.

verify_pyq_distributions.py recomputes the numbers behind the answers and audits the written files.
After the first merge the JSON files are the source of truth (docs/CONTENT_GUIDE.md, 3c); this script then serves
as the record of how they were made. Pass --force to overwrite them anyway."""
import io, json, os, sys
from collections import OrderedDict

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)
import pyq_bank_probability, pyq_bank_standard, pyq_bank_univariate, pyq_bank_multivariate  # noqa: E402

SOURCES = [
    ("Probability - CSIR NET (2011-2025)", 30, pyq_bank_probability),
    ("Standard Univariate Distributions - CSIR NET (2011-2025)", 36, pyq_bank_standard),
    ("Univariate Distributions - PYQ CSIR NET (2011-2025)", 62, pyq_bank_univariate),
    ("Multivariate Distributions CSIR NET (2011-2025)", 88, pyq_bank_multivariate),
]

# Questions in a compilation that are not in the banks, and why. Every question number of every compilation is either
# an item (its ref names it), a repeat (named in the ref of the item that keeps it) or listed here.
LEFT_OUT = OrderedDict([
    ("Univariate PDF Q42", "No printed option is necessarily true: Corr(U, V) = Var Z/(Var X + Var Z) ≥ 0 rules out B, it equals 1 when X and Y are degenerate (D fails), equal laws of X + Z and Y + Z do not force equal laws of X and Y (A fails), and U + V, U − V are independent only under normality (C, the compilation's key, fails)."),
    ("Multivariate PDF Q14", "No printed statement is true as stated: max(N¹ − N², 0) is not a Markov birth-death process (from 0 its up-rate depends on how negative N¹ − N² is), and max(N¹, N²) is neither Poisson nor pure birth with rate a + b. The compilation's key (2) would need the reflected walk, which the stem does not define."),
    ("Multivariate PDF Q72", "None of the printed rules is the Bayes rule. For N(2, 8) against N(4, 1) with equal priors, group 2 is chosen exactly when 7x² − 60x + 124 < 8 ln √8, i.e. for x between about 2.93 and 5.64; no option states this interval."),
])

LABEL = "CSIR NET 2011–2025 previous-year questions"
MODULE_ORDER = ["probability", "inference", "stochastic", "multivariate", "nonparam", "regression", "timeseries", "maths"]


def collect():
    items, seen = [], set()
    for title, n, mod in SOURCES:
        for x in mod.ITEMS:
            assert x["item"]["id"] not in seen, "duplicate id " + x["item"]["id"]
            seen.add(x["item"]["id"])
            items.append((title, x))
    return items


def build():
    items = collect()
    banks = OrderedDict()
    for _, x in items:
        banks.setdefault(x["module"], []).append(x["item"])
    out = OrderedDict()
    for m in sorted(banks, key=lambda k: MODULE_ORDER.index(k) if k in MODULE_ORDER else 99):
        its = banks[m]
        out["seed/%s_csir_pyq.json" % m] = OrderedDict([
            ("moduleId", m), ("source", "variant"), ("label", LABEL), ("count", len(its)), ("items", its)])
    return items, out


def report(items, out):
    L = ["# CSIR NET 2011–2025 previous-year practice banks", "",
         "Generated by `pyq_bank_build.py`; checked by `verify_pyq_distributions.py`. Do not edit by hand.", "",
         "## What is here", "",
         "Questions from four MathStats Classes compilations of CSIR NET (2011–2025) papers, each with the answer, a worked",
         "solution and, for multiple-correct questions, a verdict and reason for every statement. They are filed in the",
         "Question bank of the module each question tests, as practice sets (`source: \"variant\"`).", "",
         "| Bank file | Questions | Single | Multiple-correct | Write-in |", "|---|---|---|---|---|"]
    for f, d in out.items():
        fm = [i["format"] for i in d["items"]]
        L.append("| `%s` | %d | %d | %d | %d |" % (f, len(fm), fm.count("single"), fm.count("multi"), fm.count("numeric")))
    L += ["", "| Compilation | Questions in it | Items kept from it |", "|---|---|---|"]
    for title, n, mod in SOURCES:
        L.append("| %s | %d | %d |" % (title, n, len(mod.ITEMS)))
    L += ["", "Questions that appear in two compilations are kept once; the item's `ref` names every place it appears.", "",
          "## Quality checks", "",
          "1. **Numerical answers are recomputed.** `verify_pyq_distributions.py` recomputes the numbers behind the answers",
          "   with exact fractions, exhaustive enumeration, numerical integration or seeded simulation, and fails if any",
          "   disagree. Purely conceptual statements (for example 'zero correlation implies independence') cannot be",
          "   computed; each carries a written reason or counterexample, which a reviewer should read.",
          "2. **Structure is audited.** The same script checks that each single item has four distinct options and one key,",
          "   that each multiple-correct item's keyed combination is exactly the set of statements marked true, that no",
          "   explanation names its own answer as a wrong option, and that the files on disk equal what the build writes.",
          "3. **The compilation's answer key was compared, not copied.** Where the computation disagrees with the key printed",
          "   in the compilation, the item carries a `keyNote` saying so and why; the computed answer is used.",
          "4. **Misprints are flagged.** An item whose stem or options had to be read or completed carries a `repaired` note.",
          "5. `npm run check` validates every bank against `contracts/pool.schema.json`.", "",
          "## Where the compilation's key was not used", "", "| Item | Source | Note |", "|---|---|---|"]
    for _, x in items:
        it = x["item"]
        if it.get("keyNote"):
            L.append("| `%s` | %s | %s |" % (it["id"], it["ref"], it["keyNote"].replace("|", "\\|")))
    L += ["", "## Repaired or completed items", "", "| Item | Source | Note |", "|---|---|---|"]
    for _, x in items:
        it = x["item"]
        if it.get("repaired"):
            L.append("| `%s` | %s | %s |" % (it["id"], it["ref"], it["repaired"].replace("|", "\\|")))
    L += ["", "## Left out", "", "| Question | Reason |", "|---|---|"]
    for k, v in LEFT_OUT.items():
        L.append("| %s | %s |" % (k, v.replace("|", "\\|")))
    return "\n".join(L) + "\n"


def render(d):
    return json.dumps(d, ensure_ascii=False, indent=1) + "\n"


def main(argv):
    items, out = build()
    files = OrderedDict((f, render(d)) for f, d in out.items())
    files["docs/CSIR_PYQ_BANK.md"] = report(items, out)
    if "--check" in argv:
        bad = [f for f, t in files.items()
               if not os.path.exists(os.path.join(ROOT, f))
               or io.open(os.path.join(ROOT, f), encoding="utf-8", newline="").read().replace("\r\n", "\n") != t]
        for f in bad:
            print("DIFFERS: " + f)
        return 1 if bad else 0
    exists = [f for f in files if f.startswith("seed/") and os.path.exists(os.path.join(ROOT, f))]
    if exists and "--force" not in argv:
        print("refusing to overwrite merged banks (the JSON is the source of truth once merged); pass --force")
        return 1
    for f, t in files.items():
        io.open(os.path.join(ROOT, f), "w", encoding="utf-8", newline="\n").write(t)
        print("wrote " + f)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
