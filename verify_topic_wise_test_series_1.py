from fractions import Fraction
from math import comb, exp, factorial, isclose, log, sqrt
from math import sqrt


def q1():
    # Change of variables: support endpoint and derivative determine the density.
    support = sqrt(2)
    derivative_factor = lambda y: 2 * y
    return "A" if support > 1 and isclose(0.5 * derivative_factor(1), 1.0) else "?"


def q2():
    # Substitute y into the original density and multiply by |dx/dy|.
    at_quarter = (sqrt(0.25) + 0.25 / 2) / (2 * 0.25)
    return "D" if isclose(at_quarter, 1.25) else "?"


def q4():
    required_c = sqrt(Fraction(4, 1) / Fraction(4, 100))
    return "D" if 8 < required_c <= 10 else "?"


def q5():
    return "C" if Fraction(9, 6**2) == Fraction(1, 4) else "?"


def q6():
    return "A" if Fraction(9, 15) == Fraction(3, 5) else "?"


def q7():
    k = Fraction(6, 3)
    return "D" if 1 - Fraction(1, k**2) == Fraction(3, 4) else "?"


def q8():
    ex2 = Fraction(1, 3)
    return "B" if ex2 < Fraction(1, 2) else "?"


def q9():
    # Jensen twice: reciprocal convex, then exponential increasing.
    reciprocal_bound = Fraction(1, 1 + 10)
    return "B" if reciprocal_bound == Fraction(1, 11) else "?"


def q10():
    normalizer_integral = Fraction(1, 2)
    k = 1 / normalizer_integral
    second_moment_tail_power = 2 - 3
    return "B" if k == 2 and second_moment_tail_power == -1 else "?"


def q11():
    mean_abs = 2 * Fraction(3, 2) * Fraction(1, 4)
    second_abs = 2 * Fraction(3, 2) * Fraction(1, 5)
    var_abs = second_abs - mean_abs**2
    return "D" if (mean_abs, var_abs) == (Fraction(3, 4), Fraction(3, 80)) else "?"


def q12():
    p_positive = 1 - exp(-1)
    return "C" if isclose(p_positive, (exp(1) - 1) / exp(1)) else "?"


def q13():
    var_x = 5 * Fraction(1, 2) * Fraction(1, 2)
    var_y = 5
    result = Fraction(2, 5) ** 2 * var_x + Fraction(3, 5) ** 2 * var_y
    return "A" if result == 2 else "?"


def q14():
    # The three pieces have total area 2a; the requested tail has area a.
    a = Fraction(1, 2)
    tail = a
    return "B" if tail == Fraction(1, 2) else "?"


def q15():
    left_limit_at_2 = Fraction(3, 5)
    probability = 1 - left_limit_at_2
    return "D" if probability == Fraction(2, 5) else "?"


def q16():
    integral_b = Fraction(3, 4) * (2 - Fraction(2, 3))
    return "B" if integral_b == 1 else "?"


def q17():
    # Solve exp(-m^2/16)=1/2.
    coefficient_squared = 16 * log(2)
    return "D" if isclose(sqrt(coefficient_squared), 4 * sqrt(log(2))) else "?"


def q18():
    # Tail integral of x^(r-8) converges precisely when r < 7.
    highest_integer_r = 6
    return "C" if highest_integer_r == 6 else "?"


def q19():
    l = 2.0
    conditional_mean = (2 / l) * (exp(l / 2) - 1)
    return "B" if isclose(conditional_mean, exp(1) - 1) else "?"


def q22():
    poisson_odd = Fraction(1, 3) * (1 - exp(-2))
    geometric_odd = Fraction(1, 6)
    total = poisson_odd + geometric_odd
    return "A" if isclose(total, 0.5 - exp(-2) / 3) else "?"


def q23():
    # Product of the two independent uniform(0,1) MGFs.
    return "B" if ((exp(1) - 1) / 1) ** 2 > 0 else "?"


def q24():
    expectation = Fraction((3 + 4) ** 2, 16) + Fraction((3 + 2) ** 2, 16)
    return "C" if expectation == Fraction(37, 8) else "?"


def q25():
    tail_even = Fraction(1, 4) * Fraction(3, 4) / (1 - Fraction(3, 4) ** 2)
    tail_all = Fraction(3, 4)
    conditional = tail_even / tail_all
    return "A" if conditional == Fraction(4, 7) else "?"


def q26():
    a, b = 5, 7
    low, high = 2 * a + b, 10 * a + b
    return "B" if (low, high) == (17, 57) else "D"


def q27():
    conditional_length = Fraction(12 - 6, 1)
    event_length = Fraction(7 - 6, 1)
    return "D" if event_length / conditional_length == Fraction(1, 6) else "A"


def q28():
    k = Fraction(1, 1) / (Fraction(1, 2) - Fraction(1, 3))
    reciprocal_mean = k * Fraction(1, 2)
    harmonic_mean = Fraction(1, 1) / reciprocal_mean
    return "D" if harmonic_mean == Fraction(1, 3) else "A"


def q29():
    # Solving t^2 + 3t - 18 = 0 gives t=3, where t=lambda^2.
    t = 3
    lam = sqrt(t)
    skew = 1 / sqrt(lam)
    return "A" if abs(skew - 1 / sqrt(sqrt(3))) < 1e-12 else "D"


def q30():
    pmf = {x: Fraction(2 * x + 3, 21) for x in (1, 2, 3)}
    expected_indicators = sum(
        (sum((p for x, p in pmf.items() if x >= k), Fraction(0)) for k in (1, 2, 3)),
        Fraction(0),
    )
    return "C" if expected_indicators == Fraction(46, 21) else "A"


# ---- generated by `node tools/intake.js build`: compare every q<n>() with the bank as written
def _same(fmt, want, got):
    import fractions
    want, got = str(want).strip(), str(got).strip()
    if fmt == "multi":
        return sorted(want.upper()) == sorted(got.upper())
    if fmt == "numeric":
        try:
            return abs(float(fractions.Fraction(want)) - float(fractions.Fraction(got))) <= 1e-9 * max(1.0, abs(float(fractions.Fraction(want))))
        except (ValueError, ZeroDivisionError):
            pass
    return want == got


def _check():
    import json as _json, os as _os
    root = _os.path.dirname(_os.path.abspath(__file__))
    items = {}
    for rel in ["seed/probability_topic_wise_test_series_1.json"]:
        with open(_os.path.join(root, rel), encoding="utf-8") as f:
            for it in _json.load(f)["items"]:
                items[int(it["id"].rsplit("-q", 1)[1])] = it
    assert len(items) == 27, len(items)
    for n, it in sorted(items.items()):
        want = "".join(L for L in "ABCD" if it["verdicts"][L]["tf"]) if it["format"] == "multi" else it["answer"]
        got = globals()["q%d" % n]()
        assert _same(it["format"], want, got), (n, want, got)
    print("Verified %d answers independently against seed/probability_topic_wise_test_series_1.json" % len(items))


if __name__ == "__main__":
    _check()
